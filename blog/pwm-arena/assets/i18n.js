const dicts = { en, zh };
let lang = store.get("pwm-arena.lang", "en") === "zh" ? "zh" : "en";
export const missing = new Set();

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = next === "zh" ? "zh" : "en";
  store.set("pwm-arena.lang", lang);
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
}

export function t(key, vars) {
  let text = dicts[lang][key];
  if (text === undefined) {
    missing.add(`${lang}:${key}`);
    text = en[key] ?? key;
  }
  if (vars) text = text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`));
  return text;
}

/** Translate a status-like enum, falling back to the raw value. */
export function tEnum(prefix, value) {
  if (value === null || value === undefined) return "—";
  const key = `${prefix}.${value}`;
  return dicts[lang][key] ?? en[key] ?? String(value).replace(/_/g, " ");
}

export function keyCount() {
  return { en: Object.keys(en).length, zh: Object.keys(zh).length };
}
